TOKEN_PATTERN = re.compile(r"(`[^`]*`|\[\[[^\]]+\]\])")


def normalize_text(text: str) -> str:
    parts = TOKEN_PATTERN.split(text)
    for i, part in enumerate(parts):
        if not part or part.startswith("`") or part.startswith("[["):
            continue
        for src, dst in PHRASES:
            part = part.replace(src, dst)
        for src, dst in POST:
            part = part.replace(src, dst)
        parts[i] = part
    return "".join(parts)


def normalize_frontmatter(fm: str) -> str:
    lines = []
    for line in fm.splitlines():
        if line.startswith("title:") or line.startswith("summary:"):
            prefix, value = line.split(":", 1)
            stripped = value.strip()
            if len(stripped) >= 2 and stripped[0] == stripped[-1] and stripped[0] in {'"', "'"}:
                q = stripped[0]
                lines.append(f"{prefix}: {q}{normalize_text(stripped[1:-1])}{q}")
            else:
                lines.append(f"{prefix}: {normalize_text(value)}")
        else:
            lines.append(line)
    return "\n".join(lines)


def split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---\n"):
        return "", text
    end = text.find("\n---\n", 4)
    if end == -1:
        return "", text
    return text[4:end], text[end + 5 :]


def normalize_file(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    fm, body = split_frontmatter(text)
    if fm:
        new_text = f"---\n{normalize_frontmatter(fm)}\n---\n{normalize_text(body)}"
    else:
        new_text = normalize_text(text)
    path.write_text(new_text.rstrip() + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    count = 0
    for path in sorted(PATTERNS.glob("*.md")):
        normalize_file(path)
        count += 1
    print(f"polished {count} pattern docs")


if __name__ == "__main__":
    main()
